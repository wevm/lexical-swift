// Port of packages/lexical-playground/src/nodes/KeywordNode.ts: words of
// congratulation in many languages, as text entities the views draw bold
// and in color (the playground's `.keyword`).

/// `KeywordNode`.
final class KeywordNode: TextNode {
  override class func config() throws -> NodeConfig? {
    NodeConfig(KeywordNode.self, type: "keyword", extends: TextNode.self)
  }

  override func createDOM(_ config: EditorConfig, _ editor: Editor? = nil) throws -> DOMElement {
    let dom = try super.createDOM(config, editor)
    dom.style.setProperty("cursor", "default")
    // Add to the class names TextNode.createDOM already applied for the
    // text formats rather than replacing them: registerLexicalTextEntity
    // carries the format of the node it replaces over to the KeywordNode.
    addClassNamesToElement(dom, "keyword")
    return dom
  }

  override func canInsertTextBefore() throws -> Bool { false }

  override func canInsertTextAfter() throws -> Bool { false }

  override func isTextEntity() -> Bool { true }
}

/// `$createKeywordNode(keyword)`.
func createKeywordNode(_ keyword: String = "") throws -> KeywordNode {
  try applyNodeReplacement(KeywordNode(keyword))
}

func isKeywordNode(_ node: LexicalNode?) -> Bool { node is KeywordNode }

