/// `getKeywordMatch`.
private func getKeywordMatch(_ text: String) -> EntityMatch? {
  guard let match = KEYWORDS_REGEX.exec(text) else { return nil }
  let keywordLength = (match[2] ?? "").utf16.count
  let startOffset = match.index + (match[1] ?? "").utf16.count
  return EntityMatch(start: startOffset, end: startOffset + keywordLength)
}

/// `KeywordsExtension`.
let KeywordsExtension = defineExtension(
  name: "@lexical/playground/LexicalKeywords", nodes: { [.klass(KeywordNode.self)] },
  register: { editor, _, _ in
    mergeRegister(
      try registerLexicalTextEntity(editor, getKeywordMatch, KeywordNode.self) {
        try createKeywordNode($0.getTextContent())
      })
  })
