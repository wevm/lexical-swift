#!/usr/bin/env bash
# Refreshes the vendored tree-sitter C core and grammars that
# LexicalCodeTreeSitter builds on. Run from anywhere; needs git, node and
# npx. To move to a new release, change the pins below and run it again.
#
# - Sources/CTreeSitter: tree-sitter's lib/src and lib/include (compiled
#   through the lib.c amalgamation; the WASM stdlib is left out).
# - Sources/TreeSitter<Grammar>: each grammar's src (parser.c, scanner.c,
#   headers), its queries/highlights.scm, its license, and a generated
#   highlights.c that embeds the query and a header declaring both.
set -euo pipefail

CORE_VERSION=v0.27.1
# The CLI that generates parser.c for a grammar that doesn't commit it.
CLI_VERSION=0.27.1

# name|repository|tag|src dir in the repo|C function suffix
GRAMMARS=(
  "JavaScript|tree-sitter/tree-sitter-javascript|v0.25.0|src|javascript"
  "TypeScript|tree-sitter/tree-sitter-typescript|v0.23.2|typescript/src|typescript"
  "Swift|alex-pinkus/tree-sitter-swift|0.7.4|src|swift"
  "Python|tree-sitter/tree-sitter-python|v0.25.0|src|python"
  "JSON|tree-sitter/tree-sitter-json|v0.24.8|src|json"
  "HTML|tree-sitter/tree-sitter-html|v0.23.2|src|html"
  "CSS|tree-sitter/tree-sitter-css|v0.25.0|src|css"
  "Rust|tree-sitter/tree-sitter-rust|v0.24.2|src|rust"
  "Go|tree-sitter/tree-sitter-go|v0.25.0|src|go"
  "Bash|tree-sitter/tree-sitter-bash|v0.25.1|src|bash"
)

root=$(cd "$(dirname "$0")/.." && pwd)
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

clone() { # repository tag dir
  git -c advice.detachedHead=false clone -q --depth 1 -b "$2" "https://github.com/$1" "$3"
  git -C "$3" rev-parse HEAD
}

# The core.
dest="$root/Sources/CTreeSitter"
commit=$(clone tree-sitter/tree-sitter "$CORE_VERSION" "$work/core")
rm -rf "$dest"
mkdir -p "$dest/lib"
cp -R "$work/core/lib/src" "$work/core/lib/include" "$dest/lib/"
rm -rf "$dest/lib/src/wasm-stdlib"
cp "$work/core/LICENSE" "$dest/LICENSE"
printf 'tree-sitter/tree-sitter %s (%s)\n' "$CORE_VERSION" "$commit" >"$dest/VERSION"

# Writes `tree_sitter_<id>_highlights`, the query files concatenated, as a
# C string, and the header for it and the language function.
embed_queries() { # dest id files...
  local dest=$1 id=$2
  shift 2
  mkdir -p "$dest/include"
  cat >"$dest/include/tree_sitter_$id.h" <<EOF
// Generated by scripts/vendor-tree-sitter.sh.
#pragma once

/// The grammar's \`const TSLanguage *\`.
const void *tree_sitter_$id(void);
/// The grammar's highlights query, NUL-terminated.
const char *tree_sitter_${id}_highlights(void);
EOF
  node -e '
    const fs = require("fs");
    const [out, id, ...files] = process.argv.slice(1);
    const text = files.map(f => fs.readFileSync(f, "utf8")).join("\n");
    const bytes = [...Buffer.from(text + "\0", "utf8")];
    const lines = [];
    for (let i = 0; i < bytes.length; i += 16) {
      lines.push("  " + bytes.slice(i, i + 16).join(", ") + ",");
    }
    fs.writeFileSync(out,
      "// Generated by scripts/vendor-tree-sitter.sh from the queries in queries/.\n" +
      `#include "include/tree_sitter_${id}.h"\n\n` +
      `static const char highlights[] = {\n${lines.join("\n")}\n};\n\n` +
      `const char *tree_sitter_${id}_highlights(void) { return highlights; }\n`);
  ' "$dest/highlights.c" "$id" "$@"
}

for entry in "${GRAMMARS[@]}"; do
  IFS='|' read -r name repo tag src id <<<"$entry"
  dir="$work/$id"
  commit=$(clone "$repo" "$tag" "$dir")
  if [ ! -f "$dir/$src/parser.c" ]; then
    (cd "$dir/$(dirname "$src")" && npx --yes "tree-sitter-cli@$CLI_VERSION" generate >/dev/null)
  fi
  dest="$root/Sources/TreeSitter$name"
  rm -rf "$dest"
  # The sources the parser compiles, without the grammar's JSON, at their
  # path in the repository: TypeScript's scanner includes
  # ../../common/scanner.h, which it shares with TSX.
  mkdir -p "$dest/$src" "$dest/queries"
  (cd "$dir/$src" && find . \( -name '*.c' -o -name '*.h' \) -print0 |
    xargs -0 -I{} cp --parents {} "$dest/$src/")
  if [ "$src" != src ]; then
    mkdir -p "$dest/common"
    cp "$dir/common/"*.h "$dest/common/"
  fi
  cp "$dir/queries/highlights.scm" "$dest/queries/highlights.scm"
  cp "$dir/LICENSE"* "$dest/LICENSE"
  printf '%s %s (%s)\n' "$repo" "$tag" "$commit" >"$dest/VERSION"
  queries=("$dest/queries/highlights.scm")
  # TypeScript's highlights extend JavaScript's, which tree-sitter's
  # configuration for it lists after its own.
  if [ "$id" = typescript ]; then
    cp "$work/javascript/queries/highlights.scm" "$dest/queries/highlights-javascript.scm"
    queries+=("$dest/queries/highlights-javascript.scm")
  fi
  embed_queries "$dest" "$id" "${queries[@]}"
done
echo "Vendored tree-sitter $CORE_VERSION and ${#GRAMMARS[@]} grammars."
